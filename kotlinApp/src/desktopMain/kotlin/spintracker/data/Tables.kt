    val allinAction = text("allin_action")
    val flgIsAggressor = bool("flg_is_aggressor")
    val aggressorPosition = varchar("aggressor_position", 10)
    val bountyWon = double("bounty_won")
    val equityPercent = double("equity_percent")
    val expectedWon = double("expected_won")
    val icmEquityPercent = double("icm_equity_percent")
    val showedCards = bool("showed_cards")
    val wonAtShowdown = bool("won_at_showdown")
    val foldedBeforeShowdown = bool("folded_before_showdown")
    val effectiveStackPreflop = double("effective_stack_preflop")
    val effectiveStackFlop = double("effective_stack_flop")
    val effectiveStackTurn = double("effective_stack_turn")
