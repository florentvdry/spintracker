package spintracker.data

import org.jetbrains.exposed.dao.id.*
import org.jetbrains.exposed.sql.*

object Players : IdTable<Long>("players") {
    override val id: Column<EntityID<Long>> = long("id").autoIncrement().entityId()
    val name = varchar("name", 255)
    val room = varchar("room", 50).nullable()
    val isReg = bool("is_reg")
    val notes = text("notes")
}

object Hands : IdTable<Long>("hands") {
    override val id: Column<EntityID<Long>> = long("id").autoIncrement().entityId()
    val handId = varchar("hand_id", 50).uniqueIndex()
    val gameId = varchar("game_id", 50)
    val tblName = varchar("table_name", 100)
    val room = varchar("room", 50)
    val siteId = integer("site_id")
    val dateTime = varchar("date_time", 50)
    val heroName = varchar("hero_name", 255)
    val heroPosition = integer("hero_position")
    val playerCount = integer("player_count")
    val bigBlind = double("big_blind")
    val handRank = integer("hand_rank")
    val handType = varchar("hand_type", 50)
    val result = double("result")
    val ev = double("ev")
    val wentToShowdown = bool("went_to_showdown")
    val rawContent = text("raw_content")
    val buyIn = double("buy_in")
    val prizePool = double("prize_pool")
    val multiplier = integer("multiplier")
    val position = integer("position")
    val flop = text("flop").nullable()
    val turn = text("turn").nullable()
    val river = text("river").nullable()
    val totalPot = double("total_pot")
}

object PlayerHands : IdTable<Long>("player_hands") {
    override val id: Column<EntityID<Long>> = long("id").autoIncrement().entityId()
    val handId = long("hand_id").references(Hands.id, onDelete = ReferenceOption.CASCADE)
